#if os(iOS)
import Foundation
import Testing
@testable import BooksAndVocab

/// Pins the reader bridge's click listener to user-generated events.
///
/// The generated script must check `Event.isTrusted` as the first statement of
/// the click handler, so that the handler never posts a native message for an
/// event that the user did not produce.
struct ReaderBridgeTrustedEventTests {
    private static let clickListenerHeader = "document.addEventListener('click', function(e) {"
    private static let trustedEventGuard = "if (!e.isTrusted) return;"

    @Test func clickHandlerIgnoresUntrustedEventsBeforeAnyMessagePost() throws {
        let script = ReadiumNavigatorJS.buildSelectionScript(isDebugMode: "false")
        let header = try #require(script.range(of: Self.clickListenerHeader))
        let handlerBody = script[header.upperBound...]

        let guardRange = try #require(
            handlerBody.range(of: Self.trustedEventGuard),
            "the click handler must ignore events that were not generated by the user"
        )
        let firstPost = try #require(handlerBody.range(of: "postMessage"))

        #expect(
            guardRange.lowerBound < firstPost.lowerBound,
            "the isTrusted guard must come before any postMessage in the click handler"
        )
        let leading = handlerBody[..<guardRange.lowerBound]
            .trimmingCharacters(in: .whitespacesAndNewlines)
        #expect(leading.isEmpty, "the isTrusted guard must be the first statement of the click handler")
    }
}
#endif
